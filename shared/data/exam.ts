/**
 * Difficulty ladder (D2). The tier reflects what the question *demands* of the
 * candidate, not how obscure its subject is: naming Barolo's country is
 * Beginner even though Barolo is Italian wine law, while ranking three
 * appellations by permitted blend percentage is Advanced even when all three
 * are household names.
 */
export type ExamTier = 'beginner' | 'intermediate' | 'advanced';

/** The sixteen syllabus areas (D3). */
export type ExamCategory =
  | 'GRAPES'
  | 'REGIONS'
  | 'COUNTRIES'
  | 'STYLES'
  | 'FLAVOR_PROFILES'
  | 'VITICULTURE'
  | 'WINEMAKING'
  | 'FAULTS'
  | 'FOOD_PAIRING'
  | 'SERVING_STORAGE'
  | 'SPARKLING'
  | 'FORTIFIED'
  | 'SWEET_WINE'
  | 'HISTORY'
  | 'APPELLATIONS'
  | 'BLIND_TASTING';

/** The seven question shapes (D5). */
export type ExamFormat =
  | 'multipleChoice'
  | 'trueFalse'
  | 'selectAll'
  | 'matching'
  | 'ordering'
  | 'imageIdentification'
  | 'aromaIdentification';

/**
 * An image a question is asked *about*.
 *
 * Deliberately indirect. `kind: 'countryOutline'` names a key in `icons.json`'s
 * `countryShapeIcons` table; `kind: 'entryIcon'` names a catalog entry id and
 * resolves through `byEntry`. Both tables are generated, so a key that stops
 * existing is a build-time failure rather than a blank tile — which is exactly
 * why no question stores a file path.
 */
export interface ExamImageRef {
  kind: 'countryOutline' | 'entryIcon';
  /** Lowercased shape key for `countryOutline`; a catalog entry id for `entryIcon`. */
  key: string;
}

/** One left/right pair in a matching question. */
export interface ExamMatchPair {
  left: string;
  right: string;
}

/** The two poles a set of ordered items runs between, for the UI's axis caption. */
export interface ExamOrderAxis {
  from: string;
  to: string;
}

interface ExamQuestionBase {
  /** `EXQ-<CATEGORY-CODE>-<nnn>`. Stable: re-tiering a question never changes it. */
  id: string;
  tier: ExamTier;
  category: ExamCategory;
  /** The stem. For `trueFalse` this is the statement to be judged. */
  prompt: string;
  /** D7 — required on every question. Teaches the concept, not just the answer. */
  explanation: string;
  /** Cited where the claim is not self-evident from the catalog. */
  source?: string;
  /** Catalog entry ids this question is anchored to. Validate against `entries.json`. */
  entryRefs?: string[];
}

export interface ExamMultipleChoiceQuestion extends ExamQuestionBase {
  format: 'multipleChoice';
  options: string[];
  /** Index into `options`. The engine shuffles; authored order is not answer order. */
  answerIndex: number;
}

export interface ExamTrueFalseQuestion extends ExamQuestionBase {
  format: 'trueFalse';
  answer: boolean;
}

export interface ExamSelectAllQuestion extends ExamQuestionBase {
  format: 'selectAll';
  options: string[];
  /** Every correct index. Never empty, never all of them. */
  answerIndices: number[];
}

export interface ExamMatchingQuestion extends ExamQuestionBase {
  format: 'matching';
  /** Authored in correct pairing; the engine shuffles the right column. */
  pairs: ExamMatchPair[];
}

export interface ExamOrderingQuestion extends ExamQuestionBase {
  format: 'ordering';
  /** Authored in correct order; the engine shuffles before presenting. */
  items: string[];
  axis: ExamOrderAxis;
}

export interface ExamAromaQuestion extends ExamQuestionBase {
  format: 'aromaIdentification';
  /** Keys of `icons.json` `flavorArt` — i.e. lowercased FLAVOR entry names. */
  noteKeys: string[];
  options: string[];
  answerIndex: number;
}

export interface ExamImageQuestion extends ExamQuestionBase {
  format: 'imageIdentification';
  image: ExamImageRef;
  options: string[];
  answerIndex: number;
}

export type ExamQuestion =
  | ExamMultipleChoiceQuestion
  | ExamTrueFalseQuestion
  | ExamSelectAllQuestion
  | ExamMatchingQuestion
  | ExamOrderingQuestion
  | ExamAromaQuestion
  | ExamImageQuestion;

