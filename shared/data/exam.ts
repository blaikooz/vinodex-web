/**
 * The Wine Exam question bank (0.7.5 D, sommbot).
 *
 * ## Why the types live here and not in `types.ts`
 *
 * House convention puts every field contract in `shared/types.ts`. This file
 * deliberately breaks it: the exam schema and the exam data landed in the same
 * batch as an unrelated lineage change to `types.ts`, and a second author in
 * that file would have collided. The types below are self-contained and can be
 * relocated wholesale to `types.ts` later without touching a single question.
 *
 * ## What this file is, and is not
 *
 * It is **content**: the schema for a question and roughly four hundred of
 * them, tiered and categorised. It is not the engine. Exam assembly (D4),
 * scoring, streaks, ranks and unlocks (D6) belong in `VinodexCore`, are
 * Foundation-only, and read this bank as data. Nothing here computes anything.
 *
 * ## Anchoring
 *
 * The app's older `TastingQuiz` is *generated* from the catalog, so it cannot
 * contradict an entry. A hand-authored bank can, and that is the failure mode
 * to design against. Every question that restates a catalog fact carries
 * `entryRefs` — catalog ids, never names, for the same reason `LineageRef` uses
 * ids: the grape-name index over-lumps (Espadeiro answers to five VIVC prime
 * names, Nerello to seven). A validator that walks `entryRefs` against
 * `entries.json` is cheap and is the intended CI check.
 *
 * Questions that need a fact the catalog does not carry — an aging minimum, a
 * pedigree, a labelling percentage — carry `source` instead, or as well.
 *
 * ## Originality
 *
 * Every stem, distractor and explanation here was written from the Vinodex
 * catalog and from primary sources (appellation cahiers des charges and
 * disciplinari, consejo regulador rules, TTB 27 CFR, VIVC, *Wine Grapes*).
 * None reproduces or paraphrases a copyrighted exam question. Concept coverage
 * is deliberately WSET-shaped because that is the syllabus the spec asks for;
 * the wording, framing and worked examples are the catalog's own.
 *
 * ## Asset-backed formats
 *
 * `aromaIdentification` renders existing flavour glyphs — `noteKeys` are keys
 * of `icons.json`'s `flavorArt` table, which is minted from the 106 derived
 * FLAVOR entries, so every key is guaranteed art. `imageIdentification` uses
 * only art that exists today: `countryOutline` keys are `countryShapeIcons`
 * keys, `entryIcon` keys are catalog entry ids resolved through `byEntry`.
 * **No question references an asset path.** Bottle-shape, glass-colour, label-
 * anatomy and vine-training images would each need a new art set; see the
 * handoff notes in `data-review/CANDIDATES.md` rather than inventing paths.
 */

